from typing import Dict, List

from .schema import CORE_TARGETS, BelongsToSpec, FieldSpec, ResourceSpec

MARK = "generated by specgen — do not edit"


def py_header(spec: ResourceSpec = None) -> str:
    out = f"#!/usr/bin/env python\n# -*- coding: utf-8 -*-\n# {MARK}\n"
    if spec is not None:
        out += f"# spec: {spec.source} (sha256:{spec.digest})\n"
    return out


def _model_cls(target: str, specs: Dict[str, ResourceSpec]) -> str:
    return CORE_TARGETS.get(target) or specs[target].cls


def _field_def(f: FieldSpec) -> str:
    args: List[str] = []
    if f.type == "string":
        cls, args = "CharField", [f"max_length={f.max_length}"]
    else:
        cls = {
            "text": "TextField",
            "int": "IntField",
            "float": "FloatField",
            "bool": "BooleanField",
            "date": "DateField",
            "datetime": "DatetimeField",
        }[f.type]
    if f.unique:
        args.append("unique=True")
    if f.default is not None:
        args.append(f"default={f.default!r}")
    elif f.type == "bool":
        args.append("default=False")
    elif not f.required:
        args += ["null=True", "default=None"]
    if f.label:
        args.append(f"description={f.label!r}")
    return f"    {f.name} = fields.{cls}({', '.join(args)})"


def render_model(spec: ResourceSpec, specs: Dict[str, ResourceSpec]) -> str:
    L = [py_header(spec), f'"""{spec.label}模型（由规格生成）。"""', "", "from tortoise import fields", ""]
    L += [
        "from app.models.base import BaseModel",
        "",
        "",
        f"class {spec.cls}(BaseModel):",
        f'    """{spec.label}。{spec.description}"""',
        "",
    ]
    for f in spec.fields:
        L.append(_field_def(f))
    for b in spec.belongs_to:
        args = [f"'models.{_model_cls(b.target, specs)}'", f"related_name={spec.plural!r}", "on_delete=fields.RESTRICT"]
        if not b.required:
            args.append("null=True")
        L.append(f"    {b.name} = fields.ForeignKeyField({', '.join(args)})")
    L += [
        "",
        "    class Meta:",
        f"        table = {spec.table!r}",
        "",
        "    @property",
        "    def json(self) -> dict:",
        "        return {",
        '            "id": self.id,',
    ]
    for f in spec.fields:
        L.append(f'            "{f.name}": self.{f.name},')
    for b in spec.belongs_to:
        L.append(f'            "{b.column}": self.{b.column},')
    L += [
        '            "created_at": str(self.created_at),',
        '            "updated_at": str(self.updated_at),',
        "        }",
        "",
        "    def validate(self) -> None:",
        f'        """{spec.label}没有额外的状态约束。"""',
        "",
    ]
    return "\n".join(L)


# 框架 Type 规则不接受类型列表且放行 bool（bool 是 int 子类），数值字段用 Custom 精确判定
_INT_RULE = 'Custom(lambda v: v is None or type(v) is int, "必须是整数")'
_FLOAT_RULE = 'Custom(lambda v: v is None or type(v) in (int, float), "必须是数字")'


def _rules(f) -> List[str]:
    r = []
    if isinstance(f, BelongsToSpec):
        if f.required:
            r.append("Required()")
        r.append(_INT_RULE)
        return r
    if f.required:
        r.append("Required()")
    if f.type == "int":
        r.append(_INT_RULE)
    elif f.type == "float":
        r.append(_FLOAT_RULE)
    elif f.type in ("date", "datetime"):
        # 接受 YYYY-MM-DD 或 ISO 8601；空值放行（必填由 Required 负责）
        r.append("Date()")
    else:
        r.append(f"Type({ {'string': 'str', 'text': 'str', 'bool': 'bool'}[f.type] })")
    if f.type == "string":
        r.append(f"Length(max_={f.max_length})")
    if f.format == "email":
        r.append("Email()")
    if f.choices is not None:
        r.append(f"OneOf({list(f.choices)!r})")
    return r


def render_resource(spec: ResourceSpec, specs: Dict[str, ResourceSpec]) -> str:
    cls, res = spec.cls, spec.resource
    imports = {cls} | {_model_cls(b.target, specs) for b in spec.belongs_to}
    children = [(c, b) for c in specs.values() for b in c.belongs_to if b.target == res]
    imports |= {c.cls for c, _ in children}
    uniq = [f.name for f in spec.fields if f.unique]
    search = [f.name for f in spec.fields if f.searchable]
    need = {"Required", "Type"}
    for f in [*spec.fields, *spec.belongs_to]:
        need |= {x.split("(")[0] for x in _rules(f)}
    names = ["extract_whitelisted", "parse_pagination", "request_payload", "validate_fields", *sorted(need)]
    L = [py_header(spec), f'"""{spec.label} API 资源（由规格生成）。权限点 ``{res}:<action>``。"""', ""]
    L += [
        "from sanic.request import Request",
        "from sanic.views import HTTPMethodView",
        "from tortoise.exceptions import IntegrityError",
    ]
    if search:
        L.append("from tortoise.expressions import Q")
    L += [
        "",
        "from app.api import APIResponse, v1_bp",
        "from app.api.resources.route_methods import register_view",
        "from app.api.responses import APIError",
    ]
    L += [
        "from app.api.validators import (",
        *[f"    {n}," for n in sorted(names)],
        ")",
        "from app.auth.authorization import has_permission, requires_permission",
    ]
    L += [
        f"from app.models import {', '.join(sorted(imports))}",
        "",
        f"RESOURCE = {res!r}",
        f"LABEL = {spec.label!r}",
        f"NOT_FOUND = {res.upper() + '_NOT_FOUND'!r}",
        "",
    ]
    L.append("#: 字段规则（来自规格；校验走框架 validate_fields 契约：先白名单提取，再校验提取结果）")
    L.append("FIELD_RULES = {")
    for f in [*spec.fields, *(b for b in spec.belongs_to)]:
        key = f.column if isinstance(f, BelongsToSpec) else f.name
        L.append(f"    {key!r}: [{', '.join(_rules(f))}],")
    L += [
        "}",
        "",
        f"WRITE_FIELDS = {tuple(spec.write_fields)!r}",
        f"UNIQUE_FIELDS = {tuple(uniq)!r}",
        f"SEARCH_FIELDS = {tuple(search)!r}",
    ]
    fk = ", ".join(
        f"{b.column!r}: ({_model_cls(b.target, specs)}, {b.target!r})"
        for b in spec.belongs_to
    )
    L.append(f"FK_TARGETS = {{{fk}}}")
    ch = ", ".join(f"({c.cls}, {b.column!r}, {c.label!r})" for c, b in children)
    L += [f"CHILDREN = ({ch}{',' if len(children) == 1 else ''})", "", ""]
    L += [
        f"def {res}_info(obj: {cls}) -> dict:",
        "    return obj.json",
        "",
        "",
        "def _error(message, code, status, details=None):",
        "    return APIResponse.error(message=message, error_code=code, status_code=status, details=details)",
        "",
        "",
        "async def _ref_errors(payload: dict) -> dict:",
        "    errors = {}",
        "    for col, (model, _res) in FK_TARGETS.items():",
        "        value = payload.get(col)",
        "        if value is not None and not await model.filter(id=value).exists():",
        '            errors[col] = ["引用的记录不存在"]',
        "    return errors",
        "",
        "",
        "async def _ref_permission_denied(payload: dict, account) -> bool:",
        "    # 防 ID 枚举：调用者对引用目标没有 <target>:read 时，400(不存在) 与",
        "    # 201(存在)的差异会泄露目标 id 是否存在，因此先返回 403。",
        "    for col, (_model, target_res) in FK_TARGETS.items():",
        "        if payload.get(col) is None:",
        "            continue",
        "        if not await has_permission(account, target_res, 'read'):",
        "            return True",
        "    return False",
        "",
        "",
        "async def _unique_conflicts(payload: dict, exclude_id=None) -> dict:",
        "    errors = {}",
        "    for name in UNIQUE_FIELDS:",
        "        value = payload.get(name)",
        "        if value is None:",
        "            continue",
        f"        query = {cls}.filter(**{{name: value}})",
        "        if exclude_id is not None:",
        "            query = query.exclude(id=exclude_id)",
        "        if await query.exists():",
        '            errors[name] = ["已存在"]',
        "    return errors",
        "",
        "",
        f"class {cls}Resource(HTTPMethodView):",
        f'    """{spec.label} 列表 / 详情 / 创建 / 更新 / 删除。"""',
        "",
        f'    @requires_permission("{res}:read")',
        f"    async def get(self, request: Request, {res}_id: int = None):",
        f"        if {res}_id is not None:",
        f"            obj = await {cls}.filter(id={res}_id{', deleted=False' if spec.soft_delete else ''}).first()",
        "            if obj is None:",
        '                return _error(f"{LABEL}不存在", NOT_FOUND, 404)',
        f'            return APIResponse.success(data={res}_info(obj), message=f"获取{{LABEL}}成功")',
        f"        query = {cls}.all()",
    ]
    if spec.soft_delete:
        L.append("        query = query.filter(deleted=False)")
    if search:
        L += [
            '        keyword = (request.args.get("keyword") or "").strip()',
            "        if keyword:",
            "            conds = Q()",
            "            for name in SEARCH_FIELDS:",
            '                conds |= Q(**{name + "__contains": keyword})',
            "            query = query.filter(conds)",
        ]
    sort_allowed = tuple(spec.sorting.allowed)
    sort_default = spec.sorting.default or "-id"
    L += [
        "        ordering = (request.args.get('ordering') or '').strip()",
        f"        SORT_ALLOWED = {sort_allowed!r}",
        "        if ordering:",
        "            field = ordering[1:] if ordering.startswith('-') else ordering",
        "            if field not in SORT_ALLOWED:",
        '                return _error(f"不支持的排序字段：{field}", APIError.VALIDATION_ERROR, 400)',
        "            order_clause = ordering",
        "        else:",
        f"            order_clause = {sort_default!r}",
        "        page, page_size = parse_pagination(request)",
        "        total = await query.count()",
        '        rows = await query.order_by(order_clause).offset((page - 1) * page_size).limit(page_size)',
        "        return APIResponse.list(",
        f"            items=[{res}_info(r) for r in rows], total=total, page=page, page_size=page_size,",
        '            message=f"获取{LABEL}列表成功",',
        "        )",
        "",
        f'    @requires_permission("{res}:create")',
        "    async def post(self, request: Request):",
        "        payload = extract_whitelisted(request_payload(request), WRITE_FIELDS)",
        "        if await _ref_permission_denied(payload, request.ctx.authentication_session.bearer):",
        '            return _error("无权引用该关联资源", APIError.FORBIDDEN, 403)',
        "        errors = validate_fields(payload, FIELD_RULES)",
        "        if not errors:",
        "            errors = await _ref_errors(payload)",
        "        if errors:",
        '            return _error("参数验证失败", APIError.VALIDATION_ERROR, 400, errors)',
        "        conflicts = await _unique_conflicts(payload)",
        "        if conflicts:",
        '            return _error("字段值已存在", APIError.CONFLICT, 409, conflicts)',
        "        try:",
        f"            obj = await {cls}.create(**payload)",
        "        except IntegrityError:",
        '            return _error("字段值已存在", APIError.CONFLICT, 409)',
        "        return APIResponse.created(",
        f'            data={res}_info(obj), message=f"创建{{LABEL}}成功", location=f"/api/v1/{spec.plural}/{{obj.id}}"',
        "        )",
        "",
        f'    @requires_permission("{res}:update")',
        f"    async def put(self, request: Request, {res}_id: int):",
        f"        obj = await {cls}.filter(id={res}_id).first()",
        "        if obj is None:",
        '            return _error(f"{LABEL}不存在", NOT_FOUND, 404)',
        "        payload = extract_whitelisted(request_payload(request), WRITE_FIELDS)",
        "        if await _ref_permission_denied(payload, request.ctx.authentication_session.bearer):",
        '            return _error("无权引用该关联资源", APIError.FORBIDDEN, 403)',
        "        if not payload:",
        '            return _error("没有可更新的字段", APIError.MISSING_PARAMETER, 400)',
        "        errors = validate_fields(payload, {k: v for k, v in FIELD_RULES.items() if k in payload})",
        "        if not errors:",
        "            errors = await _ref_errors(payload)",
        "        if errors:",
        '            return _error("参数验证失败", APIError.VALIDATION_ERROR, 400, errors)',
        f"        conflicts = await _unique_conflicts(payload, exclude_id={res}_id)",
        "        if conflicts:",
        '            return _error("字段值已存在", APIError.CONFLICT, 409, conflicts)',
        "        for name, value in payload.items():",
        "            setattr(obj, name, value)",
        "        try:",
        "            await obj.save()",
        "        except IntegrityError:",
        '            return _error("字段值已存在", APIError.CONFLICT, 409)',
        f'        return APIResponse.success(data={res}_info(obj), message=f"{{LABEL}}更新成功")',
        "",
        f'    @requires_permission("{res}:delete")',
        f"    async def delete(self, request: Request, {res}_id: int):",
        f"        obj = await {cls}.filter(id={res}_id).first()",
        "        if obj is None:",
        '            return _error(f"{LABEL}不存在", NOT_FOUND, 404)',
        "        for child, column, child_label in CHILDREN:",
        f"            if await child.filter(**{{column: {res}_id}}).exists():",
        '                return _error(f"存在关联的{child_label}，无法删除{LABEL}", APIError.CONFLICT, 409)',
        *(
            [
                "        obj.deleted = True",
                '        await obj.save(update_fields=["deleted"])',
            ]
            if spec.soft_delete
            else ["        await obj.delete()"]
        ),
        '        return APIResponse.success(message=f"删除{LABEL}成功")',
        "",
        "",
        f'register_view(v1_bp, "/{spec.plural}/<{res}_id:int>", {cls}Resource, ["GET", "PUT", "DELETE"], "{res}_detail")',
        f'register_view(v1_bp, "/{spec.plural}", {cls}Resource, ["GET", "POST"], "{res}_list")',
        "",
    ]
    return "\n".join(L)


def render_models_init(specs: Dict[str, ResourceSpec]) -> str:
    order = sorted(specs)
    L = [py_header(), '"""生成的模型包：由 app/models/__init__.py 导入，使 Tortoise 能发现它们。"""', ""]
    L += [f"from app.generated.models.{r} import {specs[r].cls}" for r in order]
    L += ["", f"__all__ = {[specs[r].cls for r in order]!r}", ""]
    return "\n".join(L)


def render_resources_init(specs: Dict[str, ResourceSpec]) -> str:
    order = sorted(specs)
    L = [py_header(), '"""生成的 API 资源包：导入即注册路由，并登记权限点。"""', ""]
    L += ["from app.generated.permissions import register_permissions", ""]
    L += [f"from app.generated.resources.{r} import {specs[r].cls}Resource" for r in order]
    L += [
        "",
        "register_permissions()",
        "",
        f"GENERATED_RESOURCE_CLASSES = [{', '.join(specs[r].cls + 'Resource' for r in order)}]",
        "",
    ]
    return "\n".join(L)


def render_permissions(specs: Dict[str, ResourceSpec]) -> str:
    L = [
        py_header(),
        '"""生成的权限点。``register_permissions`` 幂等地并入 ``ALL_PERMISSIONS``。"""',
        "",
        "GENERATED_PERMISSIONS = {",
    ]
    for r in sorted(specs):
        L.append(f"    {r!r}: {list(specs[r].permissions.actions)!r},")
    L += [
        "}",
        "",
        "",
        "def register_permissions() -> None:",
        "    from app.auth.permissions import ALL_PERMISSIONS",
        "",
        "    for resource, actions in GENERATED_PERMISSIONS.items():",
        "        ALL_PERMISSIONS[resource] = list(actions)",
        "",
    ]
    return "\n".join(L)


def render_package_init() -> str:
    return py_header() + '"""specgen 生成物包（models / resources / permissions）。"""\n'
